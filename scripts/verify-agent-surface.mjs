// Agent 面的契约：系统提示是一段不超过 600 字的静态文字，工具描述各不超过 400 字。
//
// 为什么值得一条守卫：系统提示拼上渠道/模型表是这里出过两次的写法，症状不是报错而是
// 每个账号、每次目录刷新都换一份提示，提供方的提示缓存全被打掉，而界面看起来没问题。
// 工具描述同理——它们进的是模型可见的那一面，长一寸就是长一寸的 token。
//
// Run: node scripts/verify-agent-surface.mjs [--write]
// Exit 0 = 与快照一致且长度达标，1 = 需要更新快照或超出上限。
import assert from 'node:assert/strict'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const ROOT = new URL('..', import.meta.url)
const SNAPSHOT = new URL('docs/agent-surface.snapshot.md', ROOT)
const WRITE = process.argv.includes('--write')

/** 上限：字数口径是码点，含标点、空白与换行。 */
const GUIDANCE_LIMIT = 600
const TOOL_LIMIT = 400

/** 系统提示里不该出现的东西：外部地址、旧品牌、密钥存储方式。 */
const FORBIDDEN = ['http://', 'https://', '团团', 'TuanTuan', 'api_key', 'API key']

if (!existsSync(new URL('../lib/index.js', import.meta.url))) {
  console.error('verify-agent-surface: lib/index.js is missing; run `pnpm build` first')
  process.exit(1)
}
const host = await import('../lib/index.js')

let failed = 0
const fail = message => { failed += 1; console.error(`FAIL  ${message}`) }
const pass = message => { console.log(`  ok  ${message}`) }

/** 记录 defineTool 定义，不执行任何工具。 */
function collectTools(register) {
  const collected = []
  const ctx = {
    tools: { register: (tool) => { collected.push(tool); return () => {} } },
    effect: (fn) => fn(),
    on: () => () => {},
    get: () => undefined,
  }
  register(ctx)
  return collected
}

const imageTools = collectTools(ctx => host.registerAgentImageTools(ctx, {}, () => ({
  enabled: true,
  allowAgentImageGeneration: true,
  channels: [],
  defaultChannelId: '',
})))
const videoTools = collectTools(ctx => host.registerAgentVideoTools(ctx, {}, () => ({
  enabled: true,
  allowAgentVideoGeneration: true,
  channels: [],
  defaultChannelId: '',
})))
const catalogTools = collectTools(ctx => host.registerMediaModelsTool(ctx, () => ({
  enabled: true,
  announceToAgent: true,
  snapshot: () => ({ status: 'ready', entries: [] }),
})))
const tools = [...imageTools, ...videoTools, ...catalogTools]

// ---------------------------------------------------------------- 系统提示
const guidance = host.IMAGEGEN_GUIDANCE
const guidanceLength = [...guidance].length
if (guidanceLength > GUIDANCE_LIMIT) fail(`system prompt is ${guidanceLength} characters, over the ${GUIDANCE_LIMIT} limit`)
else pass(`system prompt is ${guidanceLength} characters`)

for (const banned of FORBIDDEN) {
  if (guidance.includes(banned)) fail(`system prompt mentions ${banned}`)
}
pass('system prompt names no address, no old brand, and no key storage')

// 静态：它必须是一个常量，而不是按目录拼出来的字符串。
if (typeof guidance !== 'string') fail('system prompt is not a plain string')
if (guidance.includes('${')) fail('system prompt carries template interpolation')

// ---------------------------------------------------------------- 工具描述
const names = tools.map(tool => tool.name)
if (new Set(names).size !== names.length) fail('two tools share one name')
if (!names.includes('list_media_models')) fail('list_media_models is not registered')
for (const tool of tools) {
  const length = [...tool.description].length
  if (length > TOOL_LIMIT) fail(`${tool.name} description is ${length} characters, over the ${TOOL_LIMIT} limit`)
}
pass(`${tools.length} tool descriptions are each within ${TOOL_LIMIT} characters`)
// 生成工具的 model 参数必须指向清单工具，否则模型只能猜模型名。
for (const tool of tools.filter(candidate => candidate.name.startsWith('generate_'))) {
  const model = tool.parameters?.properties?.model
  assert.ok(model !== undefined, `${tool.name} has no model parameter`)
  if (!String(model.description).includes('list_media_models')) {
    fail(`${tool.name} does not point model at list_media_models`)
  }
}
pass('generation tools point model at list_media_models')

// ---------------------------------------------------------------- 快照
const render = () => {
  const lines = [
    '# Agent surface snapshot',
    '',
    'Generated by `node scripts/verify-agent-surface.mjs --write`. The system prompt below is',
    'fixed text: it must not change with the account, the model catalog, or the interface',
    'language. Tool descriptions are listed with their length so a growing one shows up in the',
    'diff.',
    '',
    '## System prompt',
    '',
    '```text',
    guidance,
    '```',
    '',
    `Characters: ${[...guidance].length}`,
    '',
    '## Tools',
    '',
    ...tools.map(tool => `- \`${tool.name}\` (${[...tool.description].length}): ${tool.description}`),
    '',
  ]
  return lines.join('\n')
}

const expected = render()
const existing = existsSync(SNAPSHOT) ? readFileSync(SNAPSHOT, 'utf8') : undefined
if (WRITE) {
  writeFileSync(fileURLToPath(SNAPSHOT), expected)
  console.log(`\nverify-agent-surface: wrote ${fileURLToPath(SNAPSHOT)}`)
  process.exit(failed === 0 ? 0 : 1)
}
if (existing !== expected) {
  fail('docs/agent-surface.snapshot.md is stale: review the change, then run `node scripts/verify-agent-surface.mjs --write`')
} else {
  pass('docs/agent-surface.snapshot.md matches the shipped surface')
}

if (failed > 0) process.exit(1)
console.log('\nverify-agent-surface: agent surface within budget and in sync')
